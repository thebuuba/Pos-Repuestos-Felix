-- Panel de recordatorios compartidos entre dueño y cajeros,
-- con prioridad, fecha/hora opcional en horario del negocio y vínculo opcional a cliente, suplidor o artículo.

CREATE TABLE public.recordatorios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  titulo text NOT NULL CHECK(length(btrim(titulo)) BETWEEN 1 AND 200),
  nota text NOT NULL DEFAULT '' CHECK(length(nota) <= 2000),
  fecha_limite date,
  hora_limite text NOT NULL DEFAULT '' CHECK(hora_limite = '' OR hora_limite ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  prioridad text NOT NULL DEFAULT 'media' CHECK(prioridad IN ('baja','media','alta')),
  estado text NOT NULL DEFAULT 'pendiente' CHECK(estado IN ('pendiente','completado')),
  cliente_id bigint REFERENCES public.clientes(id) ON DELETE SET NULL,
  suplidor_id bigint REFERENCES public.suplidores(id) ON DELETE SET NULL,
  producto_id bigint REFERENCES public.productos(id) ON DELETE SET NULL,
  creado_por text NOT NULL DEFAULT '' CHECK(length(creado_por) <= 2000),
  completado_por text CHECK(completado_por IS NULL OR length(completado_por) <= 2000),
  completado_en timestamptz,
  activo boolean NOT NULL DEFAULT true,
  version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  CHECK (hora_limite = '' OR fecha_limite IS NOT NULL),
  CHECK (
    (estado = 'pendiente' AND completado_en IS NULL AND completado_por IS NULL)
    OR (estado = 'completado' AND completado_en IS NOT NULL)
  )
);

CREATE INDEX recordatorios_activos_idx ON public.recordatorios(estado, fecha_limite NULLS LAST, id DESC) WHERE activo;
CREATE INDEX recordatorios_cliente_idx ON public.recordatorios(cliente_id) WHERE cliente_id IS NOT NULL;
CREATE INDEX recordatorios_suplidor_idx ON public.recordatorios(suplidor_id) WHERE suplidor_id IS NOT NULL;
CREATE INDEX recordatorios_producto_idx ON public.recordatorios(producto_id) WHERE producto_id IS NOT NULL;

ALTER TABLE public.recordatorios ENABLE ROW LEVEL SECURITY;
CREATE POLICY pos_servidor ON public.recordatorios TO pos_app USING(true) WITH CHECK(true);

