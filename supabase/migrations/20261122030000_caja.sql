-- Una caja física; cada turno conserva su responsable y conciliación.
CREATE TABLE public.turnos_caja (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  usuario text NOT NULL CHECK(length(btrim(usuario)) BETWEEN 1 AND 2000),
  cajero text NOT NULL CHECK(length(btrim(cajero)) BETWEEN 1 AND 2000),
  fondo numeric(14,2) NOT NULL CHECK(fondo>=0),
  abierto_en timestamptz NOT NULL DEFAULT now(), cerrado_en timestamptz,
  cerrado_por text, esperado numeric(14,2), contado numeric(14,2), ventas numeric(14,2),
  version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
  CHECK ((cerrado_en IS NULL AND cerrado_por IS NULL AND esperado IS NULL AND contado IS NULL AND ventas IS NULL)
    OR (cerrado_en IS NOT NULL AND cerrado_en>=abierto_en AND cerrado_por IS NOT NULL AND length(btrim(cerrado_por)) BETWEEN 1 AND 2000
      AND esperado IS NOT NULL AND esperado>=0 AND contado IS NOT NULL AND contado>=0 AND ventas IS NOT NULL AND ventas>=0))
);
CREATE UNIQUE INDEX caja_un_turno_abierto ON public.turnos_caja((true)) WHERE cerrado_en IS NULL;
ALTER TABLE public.ventas
  ADD COLUMN caja_id bigint REFERENCES public.turnos_caja(id) ON DELETE RESTRICT,
  ADD COLUMN metodo_pago text,
  ADD CONSTRAINT ventas_caja_pago CHECK ((caja_id IS NULL AND metodo_pago IS NULL) OR
    (caja_id IS NOT NULL AND metodo_pago IS NOT NULL AND
      ((condicion='Credito' AND metodo_pago='credito') OR (condicion='Contado' AND metodo_pago IN ('efectivo','tarjeta','transferencia')))));
CREATE INDEX ventas_caja_idx ON public.ventas(caja_id) WHERE caja_id IS NOT NULL;
CREATE TABLE public.movimientos_caja (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  caja_id bigint NOT NULL REFERENCES public.turnos_caja(id) ON DELETE RESTRICT,
  tipo text NOT NULL CHECK(tipo IN ('entrada','salida')),
  monto numeric(14,2) NOT NULL CHECK(monto>0),
  concepto text NOT NULL CHECK(length(btrim(concepto)) BETWEEN 1 AND 2000),
  usuario text NOT NULL CHECK(length(btrim(usuario)) BETWEEN 1 AND 2000),
  creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX movimientos_caja_turno_idx ON public.movimientos_caja(caja_id,id);
ALTER TABLE public.turnos_caja ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.movimientos_caja ENABLE ROW LEVEL SECURITY;
CREATE POLICY pos_servidor ON public.turnos_caja TO pos_app USING(true) WITH CHECK(true);
CREATE POLICY pos_servidor ON public.movimientos_caja TO pos_app USING(true) WITH CHECK(true);
REVOKE ALL ON public.turnos_caja,public.movimientos_caja FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.turnos_caja_id_seq,public.movimientos_caja_id_seq FROM PUBLIC;
DO $$ DECLARE rol text; BEGIN
  FOREACH rol IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
    IF EXISTS(SELECT FROM pg_roles WHERE rolname=rol) THEN
      EXECUTE format('REVOKE ALL ON public.turnos_caja,public.movimientos_caja FROM %I',rol);
      EXECUTE format('REVOKE ALL ON SEQUENCE public.turnos_caja_id_seq,public.movimientos_caja_id_seq FROM %I',rol);
    END IF;
  END LOOP;
END $$;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.turnos_caja,public.movimientos_caja TO pos_app;
GRANT USAGE,SELECT,UPDATE ON SEQUENCE public.turnos_caja_id_seq,public.movimientos_caja_id_seq TO pos_app;
