-- Los datos desconocidos de crédito, impresión y precios permanecen sin configurar.
CREATE TABLE public.formulas_precios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  nombre text NOT NULL CHECK(length(nombre)<=2000 AND length(btrim(nombre))>0),
  factor_costo numeric(9,3) NOT NULL CHECK(factor_costo BETWEEN 0.001 AND 999999.999),
  recargo1 numeric(9,4) NOT NULL CHECK(recargo1 BETWEEN 0 AND 99999.9999),
  recargo2 numeric(9,4) NOT NULL CHECK(recargo2 BETWEEN 0 AND 99999.9999),
  recargo3 numeric(9,4) NOT NULL CHECK(recargo3 BETWEEN 0 AND 99999.9999),
  activo boolean NOT NULL DEFAULT true,
  version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
  creado_en timestamptz NOT NULL DEFAULT now(), actualizado_en timestamptz NOT NULL DEFAULT now()
);

