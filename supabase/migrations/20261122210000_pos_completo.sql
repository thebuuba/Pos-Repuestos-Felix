-- Funciones completas del POS: códigos alternativos, descuentos, anulaciones,
-- compras a crédito, abonos de cuentas por cobrar/pagar, secuencias NCF reales y meta diaria.

ALTER TABLE public.configuracion
  ADD COLUMN meta_diaria numeric(14,2) CHECK(meta_diaria IS NULL OR meta_diaria BETWEEN 0 AND 999999999999.99);

CREATE TABLE public.productos_codigos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  producto_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  codigo text NOT NULL CHECK(length(btrim(codigo)) BETWEEN 1 AND 2000),
  creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX productos_codigos_unico ON public.productos_codigos(lower(codigo));
CREATE INDEX productos_codigos_producto_idx ON public.productos_codigos(producto_id);

ALTER TABLE public.ventas
  ADD COLUMN descuento_porcentaje numeric(5,2) NOT NULL DEFAULT 0 CHECK(descuento_porcentaje BETWEEN 0 AND 100),
  ADD COLUMN descuento numeric(14,2) NOT NULL DEFAULT 0 CHECK(descuento BETWEEN 0 AND 999999999999.99),
  ADD COLUMN estado text NOT NULL DEFAULT 'activa' CHECK(estado IN ('activa','anulada')),
  ADD COLUMN anulada_en timestamptz,
  ADD COLUMN anulada_por text,
  ADD COLUMN motivo_anulacion text,
  ADD COLUMN vencimiento date,
  ADD COLUMN version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
  ADD CONSTRAINT ventas_anulacion CHECK (
    (estado='activa' AND anulada_en IS NULL AND anulada_por IS NULL AND motivo_anulacion IS NULL)
    OR (estado='anulada' AND anulada_en IS NOT NULL AND anulada_por IS NOT NULL
      AND length(btrim(anulada_por)) BETWEEN 1 AND 2000
      AND motivo_anulacion IS NOT NULL AND length(btrim(motivo_anulacion)) BETWEEN 1 AND 2000)
  );

