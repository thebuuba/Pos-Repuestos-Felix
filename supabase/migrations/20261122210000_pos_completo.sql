ALTER TABLE public.movimientos_inventario
  ADD CONSTRAINT movimientos_inventario_tipo_check CHECK(tipo IN ('apertura','venta','compra','ajuste','anulacion')),
  ADD CONSTRAINT movimientos_inventario_origen_check CHECK(
    (tipo='venta' AND venta_detalle_id IS NOT NULL AND compra_detalle_id IS NULL AND cantidad<0)
    OR (tipo='compra' AND compra_detalle_id IS NOT NULL AND venta_detalle_id IS NULL AND cantidad>0)
    OR (tipo='anulacion' AND venta_detalle_id IS NULL AND compra_detalle_id IS NULL AND cantidad>0)
    OR (tipo IN ('apertura','ajuste') AND venta_detalle_id IS NULL AND compra_detalle_id IS NULL)
  );

ALTER TABLE public.compras
  ADD COLUMN condicion text NOT NULL DEFAULT 'Contado' CHECK(condicion IN ('Contado','Credito')),
  ADD COLUMN vencimiento date,
  ADD COLUMN version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991);

CREATE TABLE public.abonos_cuentas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  tipo text NOT NULL CHECK(tipo IN ('cobro','pago')),
  venta_id bigint REFERENCES public.ventas(id) ON DELETE RESTRICT,
  compra_id bigint REFERENCES public.compras(id) ON DELETE RESTRICT,
  caja_id bigint REFERENCES public.turnos_caja(id) ON DELETE RESTRICT,
  metodo_pago text NOT NULL CHECK(metodo_pago IN ('efectivo','tarjeta','transferencia')),
  monto numeric(14,2) NOT NULL CHECK(monto>0 AND monto<=999999999999.99),
  referencia text NOT NULL DEFAULT '' CHECK(length(referencia)<=2000),
  nota text NOT NULL DEFAULT '' CHECK(length(nota)<=2000),
  usuario text NOT NULL CHECK(length(btrim(usuario)) BETWEEN 1 AND 2000),
  creado_en timestamptz NOT NULL DEFAULT now(),
  CHECK ((tipo='cobro' AND venta_id IS NOT NULL AND compra_id IS NULL)
      OR (tipo='pago' AND compra_id IS NOT NULL AND venta_id IS NULL)),
  CHECK (metodo_pago<>'efectivo' OR caja_id IS NOT NULL)
);
CREATE INDEX abonos_venta_idx ON public.abonos_cuentas(venta_id) WHERE venta_id IS NOT NULL;
CREATE INDEX abonos_compra_idx ON public.abonos_cuentas(compra_id) WHERE compra_id IS NOT NULL;
CREATE INDEX abonos_caja_idx ON public.abonos_cuentas(caja_id) WHERE caja_id IS NOT NULL;

CREATE TABLE public.secuencias_ncf (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  tipo text NOT NULL UNIQUE CHECK(tipo IN ('B01','B02','B14')),
  prefijo text NOT NULL CHECK(prefijo IN ('B01','B02','B14') AND prefijo=tipo),
  inicio bigint NOT NULL CHECK(inicio BETWEEN 1 AND 99999999),
  fin bigint NOT NULL CHECK(fin BETWEEN inicio AND 99999999),
  actual bigint NOT NULL CHECK(actual BETWEEN inicio - 1 AND fin),
  vencimiento date NOT NULL,
  activa boolean NOT NULL DEFAULT false,
  version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
  actualizado_en timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.productos_codigos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.abonos_cuentas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.secuencias_ncf ENABLE ROW LEVEL SECURITY;
