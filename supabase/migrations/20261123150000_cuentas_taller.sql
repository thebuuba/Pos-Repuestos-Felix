-- Cuentas abiertas de taller: despachos con descuento inmediato de inventario,
-- precio/ITBIS congelados al entregar, devoluciones previas y facturación consolidada.

CREATE TABLE public.cuentas_taller (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  cliente_id bigint NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
  cliente_nombre text NOT NULL CHECK(length(btrim(cliente_nombre)) BETWEEN 1 AND 2000),
  mecanico text NOT NULL DEFAULT '' CHECK(length(mecanico) <= 2000),
  vehiculo text NOT NULL DEFAULT '' CHECK(length(vehiculo) <= 2000),
  nota text NOT NULL DEFAULT '' CHECK(length(nota) <= 2000),
  estado text NOT NULL DEFAULT 'abierta' CHECK(estado IN ('abierta','facturada','cancelada')),
  venta_id bigint REFERENCES public.ventas(id) ON DELETE RESTRICT,
  abierta_por text NOT NULL CHECK(length(btrim(abierta_por)) BETWEEN 1 AND 2000),
  abierta_en timestamptz NOT NULL DEFAULT now(),
  cerrada_en timestamptz,
  version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
  CHECK (
    (estado = 'abierta' AND venta_id IS NULL AND cerrada_en IS NULL)
    OR (estado = 'facturada' AND venta_id IS NOT NULL AND cerrada_en IS NOT NULL)
    OR (estado = 'cancelada' AND venta_id IS NULL AND cerrada_en IS NOT NULL)
  )
);
CREATE INDEX cuentas_taller_estado_idx ON public.cuentas_taller(estado, abierta_en DESC);
CREATE INDEX cuentas_taller_cliente_idx ON public.cuentas_taller(cliente_id);
CREATE UNIQUE INDEX cuentas_taller_venta_unica ON public.cuentas_taller(venta_id) WHERE venta_id IS NOT NULL;

CREATE TABLE public.cuentas_taller_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  cuenta_id bigint NOT NULL REFERENCES public.cuentas_taller(id) ON DELETE RESTRICT,
  producto_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
  codigo text NOT NULL CHECK(length(btrim(codigo)) BETWEEN 1 AND 2000),
  nombre text NOT NULL CHECK(length(btrim(nombre)) BETWEEN 1 AND 2000),
  gravado boolean NOT NULL,
  nivel_precio text NOT NULL CHECK(nivel_precio IN ('precio1','precio2','precio3')),
  precio numeric(14,4) NOT NULL CHECK(precio >= 0 AND precio <= 9999999999.9999),
  cantidad numeric(12,2) NOT NULL CHECK(cantidad > 0 AND cantidad <= 2147483647.00),
  cantidad_devuelta numeric(12,2) NOT NULL DEFAULT 0 CHECK(cantidad_devuelta >= 0 AND cantidad_devuelta <= cantidad),
  despachado_por text NOT NULL CHECK(length(btrim(despachado_por)) BETWEEN 1 AND 2000),
  retirado_por text NOT NULL DEFAULT '' CHECK(length(retirado_por) <= 2000),
  creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX cuentas_taller_items_cuenta_idx ON public.cuentas_taller_items(cuenta_id, id);
CREATE INDEX cuentas_taller_items_producto_idx ON public.cuentas_taller_items(producto_id);

