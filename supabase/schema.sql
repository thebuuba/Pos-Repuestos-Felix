-- Esquema relacional del POS. Aplicar mediante pnpm db:migrate, nunca al iniciar HTTP.
CREATE SCHEMA IF NOT EXISTS pos_privado;
REVOKE ALL ON SCHEMA pos_privado FROM PUBLIC;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
DO $$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='pos_app') THEN CREATE ROLE pos_app NOLOGIN; END IF;
END $$;


-- Se conserva únicamente como archivo inmutable de la migración anterior.
CREATE TABLE IF NOT EXISTS pos_privado.estado (
  id smallint PRIMARY KEY CHECK(id=1), datos jsonb NOT NULL CHECK(jsonb_typeof(datos)='object'),
  revision integer NOT NULL DEFAULT 0 CHECK(revision>=0), actualizado_en timestamptz NOT NULL DEFAULT now()
);
REVOKE ALL ON pos_privado.estado FROM PUBLIC;
ALTER TABLE pos_privado.estado ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.configuracion (
  id smallint PRIMARY KEY CHECK(id=1),
  empresa text NOT NULL CHECK(length(btrim(empresa)) BETWEEN 1 AND 2000),
  tasa_itbis numeric(7,6) NOT NULL CHECK(tasa_itbis BETWEEN 0 AND 1),
  version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
  actualizado_en timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.clientes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  nombre text NOT NULL CHECK(length(btrim(nombre)) BETWEEN 1 AND 2000),
  rnc text NOT NULL DEFAULT '' CHECK(length(rnc)<=2000), tel text NOT NULL DEFAULT '' CHECK(length(tel)<=2000),
  saldo_apertura numeric(14,2) NOT NULL DEFAULT 0 CHECK(saldo_apertura BETWEEN -999999999999.99 AND 999999999999.99),
  activo boolean NOT NULL DEFAULT true,
  version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
  creado_en timestamptz NOT NULL DEFAULT now(), actualizado_en timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.suplidores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  nombre text NOT NULL CHECK(length(btrim(nombre)) BETWEEN 1 AND 2000),
  rnc text NOT NULL DEFAULT '' CHECK(length(rnc)<=2000), tel text NOT NULL DEFAULT '' CHECK(length(tel)<=2000),
  activo boolean NOT NULL DEFAULT true,
  version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
  creado_en timestamptz NOT NULL DEFAULT now(), actualizado_en timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.productos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  codigo text NOT NULL CHECK(length(btrim(codigo)) BETWEEN 1 AND 2000),
  nombre text NOT NULL CHECK(length(btrim(nombre)) BETWEEN 1 AND 2000),
  costo numeric(14,2) NOT NULL CHECK(costo BETWEEN 0 AND 999999999999.99),
  precio1 numeric(14,2) NOT NULL CHECK(precio1 BETWEEN 0 AND 999999999999.99),
  precio2 numeric(14,2) NOT NULL CHECK(precio2 BETWEEN 0 AND 999999999999.99),
  precio3 numeric(14,2) NOT NULL CHECK(precio3 BETWEEN 0 AND 999999999999.99),
  stock integer NOT NULL DEFAULT 0 CHECK(stock>=0), activo boolean NOT NULL DEFAULT true,
  version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
  creado_en timestamptz NOT NULL DEFAULT now(), actualizado_en timestamptz NOT NULL DEFAULT now()
