  producto_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
  codigo text NOT NULL CHECK(length(btrim(codigo)) BETWEEN 1 AND 2000), nombre text NOT NULL CHECK(length(btrim(nombre)) BETWEEN 1 AND 2000),
  cantidad integer NOT NULL CHECK(cantidad>0),
  costo numeric(14,2) NOT NULL CHECK(costo BETWEEN 0 AND 999999999999.99),
  precio1 numeric(14,2) NOT NULL CHECK(precio1 BETWEEN 0 AND 999999999999.99),
  precio2 numeric(14,2) NOT NULL CHECK(precio2 BETWEEN 0 AND 999999999999.99),
  precio3 numeric(14,2) NOT NULL CHECK(precio3 BETWEEN 0 AND 999999999999.99),
  total numeric(14,2) NOT NULL CHECK(total BETWEEN 0 AND 999999999999.99), CHECK(total=costo*cantidad)
