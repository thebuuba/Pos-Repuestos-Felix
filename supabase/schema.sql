      FOREACH tabla IN ARRAY ARRAY['sistema','solicitudes','respaldos','estado'] LOOP
        EXECUTE format('REVOKE ALL ON pos_privado.%I FROM %I',tabla,rol);
      END LOOP;
      FOREACH tabla IN ARRAY ARRAY['clientes','suplidores','productos','ventas','venta_detalles','compras','compra_detalles','movimientos_inventario'] LOOP
        EXECUTE format('REVOKE ALL ON SEQUENCE public.%I FROM %I',tabla||'_id_seq',rol);
      END LOOP;
      FOR rutina IN SELECT p.oid::regprocedure FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='pos_privado' AND p.proname IN ('legacy_text','legacy_num','legacy_array','legacy_fecha','legacy_id','importar_estado_legacy','impedir_estado_legacy') LOOP
