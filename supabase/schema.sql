-- Validadores compartidos por la migración inicial y la restauración del formato anterior.
CREATE FUNCTION pos_privado.legacy_text(o jsonb, k text, requerido boolean DEFAULT true) RETURNS text
LANGUAGE plpgsql IMMUTABLE SET search_path=pg_catalog AS $$
DECLARE v text;
BEGIN
  IF NOT requerido AND (o->k IS NULL OR o->k='null'::jsonb) THEN RETURN ''; END IF;
  IF jsonb_typeof(o->k) IS DISTINCT FROM 'string' THEN RAISE EXCEPTION 'Campo de texto inválido: %',k USING ERRCODE='22023'; END IF;
  v=btrim(o->>k);
  IF length(v)>2000 OR (requerido AND length(v)=0) THEN RAISE EXCEPTION 'Texto inválido: %',k USING ERRCODE='22023'; END IF;
  RETURN v;
END $$;
CREATE FUNCTION pos_privado.legacy_num(o jsonb, k text, entero boolean DEFAULT false, redondear boolean DEFAULT false) RETURNS numeric
LANGUAGE plpgsql IMMUTABLE SET search_path=pg_catalog AS $$
DECLARE v numeric;
BEGIN
  IF jsonb_typeof(o->k) IS DISTINCT FROM 'number' THEN RAISE EXCEPTION 'Número inválido: %',k USING ERRCODE='22023'; END IF;
  v=(o->>k)::numeric;
  IF v<0 OR v>999999999999.99 OR (entero AND (v<>trunc(v) OR v>2147483647))
     OR (NOT entero AND NOT redondear AND abs(v-round(v,2))>0.0000001) THEN RAISE EXCEPTION 'Número fuera de rango: %',k USING ERRCODE='22023'; END IF;
  RETURN CASE WHEN entero THEN v ELSE round(v,2) END;
END $$;
CREATE FUNCTION pos_privado.legacy_array(o jsonb, k text) RETURNS jsonb
LANGUAGE plpgsql IMMUTABLE SET search_path=pg_catalog AS $$
BEGIN
  IF o->k IS NULL OR o->k='null'::jsonb THEN RETURN '[]'::jsonb; END IF;
  IF jsonb_typeof(o->k)<>'array' THEN RAISE EXCEPTION 'Lista inválida: %',k USING ERRCODE='22023'; END IF;
  RETURN o->k;
END $$;
CREATE FUNCTION pos_privado.legacy_fecha(v text) RETURNS date
LANGUAGE plpgsql IMMUTABLE SET search_path=pg_catalog AS $$
DECLARE p text[];
BEGIN
  IF v ~ '^\d{4}-\d{2}-\d{2}$' THEN RETURN v::date; END IF;
  p=regexp_match(v,'^(\d{1,2})/(\d{1,2})/(\d{4})$');
  IF p IS NULL THEN RAISE EXCEPTION 'Fecha histórica inválida: %',v USING ERRCODE='22023'; END IF;
  RETURN make_date(p[3]::integer,p[2]::integer,p[1]::integer);
END $$;
CREATE FUNCTION pos_privado.legacy_id(o jsonb) RETURNS bigint
LANGUAGE plpgsql IMMUTABLE SET search_path=pg_catalog AS $$
DECLARE v numeric;
BEGIN
  IF jsonb_typeof(o->'id') IS DISTINCT FROM 'number' THEN RAISE EXCEPTION 'ID histórico inválido' USING ERRCODE='22023'; END IF;
  v=(o->>'id')::numeric;
  IF v<1 OR v>9007199254740991 OR v<>trunc(v) THEN RAISE EXCEPTION 'ID histórico fuera de rango' USING ERRCODE='22023'; END IF;
  RETURN v::bigint;
END $$;

CREATE FUNCTION pos_privado.importar_estado_legacy(datos jsonb) RETURNS void
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public,pos_privado AS $$
DECLARE r jsonb; d jsonb; cid bigint; sid bigint; pid bigint; docid bigint;
  nombre_contacto text; codigo_producto text; precio_linea numeric; total_linea numeric;
  impuesto_linea numeric; total_doc numeric; impuesto_doc numeric; qty integer; rate numeric; tabla text;
BEGIN
  IF jsonb_typeof(datos) IS DISTINCT FROM 'object' THEN RAISE EXCEPTION 'Respaldo inválido' USING ERRCODE='22023'; END IF;
  IF EXISTS(SELECT FROM public.configuracion) OR EXISTS(SELECT FROM public.clientes) OR EXISTS(SELECT FROM public.suplidores)
     OR EXISTS(SELECT FROM public.productos) OR EXISTS(SELECT FROM public.ventas) OR EXISTS(SELECT FROM public.compras)
     OR EXISTS(SELECT FROM public.venta_detalles) OR EXISTS(SELECT FROM public.compra_detalles) OR EXISTS(SELECT FROM public.movimientos_inventario)
    THEN RAISE EXCEPTION 'La importación requiere tablas vacías' USING ERRCODE='55000'; END IF;
  IF jsonb_typeof(datos->'itbisRate') IS DISTINCT FROM 'number' THEN RAISE EXCEPTION 'ITBIS inválido' USING ERRCODE='22023'; END IF;
  rate=(datos->>'itbisRate')::numeric;
  IF rate<0 OR rate>1 OR rate<>round(rate,6) THEN RAISE EXCEPTION 'ITBIS fuera de rango' USING ERRCODE='22023'; END IF;
  INSERT INTO public.configuracion(id,empresa,tasa_itbis) VALUES(1,pos_privado.legacy_text(datos,'empresa'),rate);

  FOR r IN SELECT value FROM jsonb_array_elements(pos_privado.legacy_array(datos,'clientes')) LOOP
    nombre_contacto=pos_privado.legacy_text(r,'nombre');
    IF EXISTS(SELECT FROM public.clientes WHERE lower(nombre)=lower(nombre_contacto)) THEN RAISE EXCEPTION 'Cliente histórico ambiguo: %',nombre_contacto USING ERRCODE='22023'; END IF;
    INSERT INTO public.clientes(nombre,rnc,tel,saldo_apertura) VALUES(nombre_contacto,pos_privado.legacy_text(r,'rnc',false),pos_privado.legacy_text(r,'tel',false),pos_privado.legacy_num(r,'deuda'));
  END LOOP;
  FOR r IN SELECT value FROM jsonb_array_elements(pos_privado.legacy_array(datos,'suplidores')) LOOP
    nombre_contacto=pos_privado.legacy_text(r,'nombre');
    IF EXISTS(SELECT FROM public.suplidores WHERE lower(nombre)=lower(nombre_contacto)) THEN RAISE EXCEPTION 'Suplidor histórico ambiguo: %',nombre_contacto USING ERRCODE='22023'; END IF;
    INSERT INTO public.suplidores(nombre,rnc,tel) VALUES(nombre_contacto,pos_privado.legacy_text(r,'rnc',false),pos_privado.legacy_text(r,'tel',false));
  END LOOP;
  FOR r IN SELECT value FROM jsonb_array_elements(pos_privado.legacy_array(datos,'productos')) LOOP
    INSERT INTO public.productos(codigo,nombre,costo,stock,precio1,precio2,precio3)
      VALUES(pos_privado.legacy_text(r,'codigo'),pos_privado.legacy_text(r,'nombre'),pos_privado.legacy_num(r,'costo'),
        pos_privado.legacy_num(r,'stock',true)::integer,pos_privado.legacy_num(r,'precio1'),pos_privado.legacy_num(r,'precio2'),pos_privado.legacy_num(r,'precio3'));
  END LOOP;

  FOR r IN SELECT value FROM jsonb_array_elements(pos_privado.legacy_array(datos,'facturas')) LOOP
    docid=pos_privado.legacy_id(r); nombre_contacto=pos_privado.legacy_text(r,'cliente');
    SELECT id INTO cid FROM public.clientes WHERE lower(nombre)=lower(nombre_contacto);
    IF cid IS NULL THEN INSERT INTO public.clientes(nombre,activo) VALUES(nombre_contacto,false) RETURNING id INTO cid; END IF;
    IF r->>'condicion' NOT IN ('Contado','Credito') OR r->>'condicion' IS NULL THEN RAISE EXCEPTION 'Condición de venta inválida' USING ERRCODE='22023'; END IF;
    IF jsonb_array_length(pos_privado.legacy_array(r,'items'))=0 THEN RAISE EXCEPTION 'Venta sin detalle' USING ERRCODE='22023'; END IF;
    total_doc=0; impuesto_doc=0;
    FOR d IN SELECT value FROM jsonb_array_elements(pos_privado.legacy_array(r,'items')) LOOP
      qty=pos_privado.legacy_num(d,'cant',true)::integer;
      precio_linea=pos_privado.legacy_num(d,'precio'); total_linea=pos_privado.legacy_num(d,'subtotal'); impuesto_linea=pos_privado.legacy_num(d,'itbis',false,true);
      IF qty=0 OR total_linea<>precio_linea*qty OR impuesto_linea>total_linea THEN RAISE EXCEPTION 'Detalle de venta incoherente' USING ERRCODE='22023'; END IF;
      total_doc=total_doc+total_linea; impuesto_doc=impuesto_doc+impuesto_linea;
    END LOOP;
    IF total_doc<>pos_privado.legacy_num(r,'total') THEN RAISE EXCEPTION 'Total de venta incoherente' USING ERRCODE='22023'; END IF;
    INSERT INTO public.ventas(id,cliente_id,cliente_nombre,cliente_rnc,fecha,ncf,tipo_comprobante,condicion,base,itbis,total)
      SELECT docid,cid,nombre_contacto,c.rnc,pos_privado.legacy_fecha(pos_privado.legacy_text(r,'fecha')),
        pos_privado.legacy_text(r,'ncf'),CASE WHEN left(r->>'ncf',3) IN ('B01','B02','B14') THEN left(r->>'ncf',3) ELSE 'B02' END,
        r->>'condicion',total_doc-impuesto_doc,impuesto_doc,total_doc FROM public.clientes c WHERE c.id=cid;
    FOR d IN SELECT value FROM jsonb_array_elements(pos_privado.legacy_array(r,'items')) LOOP
      codigo_producto=pos_privado.legacy_text(d,'codigo');
      SELECT id INTO pid FROM public.productos WHERE lower(codigo)=lower(codigo_producto);
      IF pid IS NULL THEN
        INSERT INTO public.productos(codigo,nombre,costo,precio1,precio2,precio3,activo)
          VALUES(codigo_producto,pos_privado.legacy_text(d,'nombre'),0,pos_privado.legacy_num(d,'precio'),pos_privado.legacy_num(d,'precio'),pos_privado.legacy_num(d,'precio'),false) RETURNING id INTO pid;
      END IF;
      total_linea=pos_privado.legacy_num(d,'subtotal'); impuesto_linea=pos_privado.legacy_num(d,'itbis',false,true);
      INSERT INTO public.venta_detalles(venta_id,producto_id,codigo,nombre,cantidad,nivel_precio,precio,base,itbis,total)
        VALUES(docid,pid,codigo_producto,pos_privado.legacy_text(d,'nombre'),pos_privado.legacy_num(d,'cant',true)::integer,'precio1',
          pos_privado.legacy_num(d,'precio'),total_linea-impuesto_linea,impuesto_linea,total_linea);
    END LOOP;
  END LOOP;
  -- Los saldos existentes pueden incluir abonos anteriores que este POS no registra en detalle.
  UPDATE public.clientes c SET saldo_apertura=c.saldo_apertura-COALESCE((SELECT sum(v.total) FROM public.ventas v WHERE v.cliente_id=c.id AND v.condicion='Credito'),0);

  FOR r IN SELECT value FROM jsonb_array_elements(pos_privado.legacy_array(datos,'compras')) LOOP
    docid=pos_privado.legacy_id(r); nombre_contacto=pos_privado.legacy_text(r,'suplidor');
    SELECT id INTO sid FROM public.suplidores WHERE lower(nombre)=lower(nombre_contacto);
    IF sid IS NULL THEN INSERT INTO public.suplidores(nombre,activo) VALUES(nombre_contacto,false) RETURNING id INTO sid; END IF;
    IF jsonb_array_length(pos_privado.legacy_array(r,'items'))=0 THEN RAISE EXCEPTION 'Compra sin detalle' USING ERRCODE='22023'; END IF;
    total_doc=0;
    FOR d IN SELECT value FROM jsonb_array_elements(pos_privado.legacy_array(r,'items')) LOOP
      qty=pos_privado.legacy_num(d,'cant',true)::integer;
      total_linea=pos_privado.legacy_num(d,'subtotal');
      IF qty=0 OR total_linea<>pos_privado.legacy_num(d,'costo')*qty THEN RAISE EXCEPTION 'Detalle de compra incoherente' USING ERRCODE='22023'; END IF;
      total_doc=total_doc+total_linea;
    END LOOP;
    IF total_doc<>pos_privado.legacy_num(r,'total') THEN RAISE EXCEPTION 'Total de compra incoherente' USING ERRCODE='22023'; END IF;
    INSERT INTO public.compras(id,suplidor_id,suplidor_nombre,numero,fecha,total)
      VALUES(docid,sid,nombre_contacto,pos_privado.legacy_text(r,'numero'),pos_privado.legacy_fecha(pos_privado.legacy_text(r,'fecha')),total_doc);
    FOR d IN SELECT value FROM jsonb_array_elements(pos_privado.legacy_array(r,'items')) LOOP
      codigo_producto=pos_privado.legacy_text(d,'codigo');
      SELECT id INTO pid FROM public.productos WHERE lower(codigo)=lower(codigo_producto);
      IF pid IS NULL THEN
        INSERT INTO public.productos(codigo,nombre,costo,precio1,precio2,precio3,activo)
          VALUES(codigo_producto,pos_privado.legacy_text(d,'nombre'),pos_privado.legacy_num(d,'costo'),pos_privado.legacy_num(d,'p1'),pos_privado.legacy_num(d,'p2'),pos_privado.legacy_num(d,'p3'),false) RETURNING id INTO pid;
      END IF;
      INSERT INTO public.compra_detalles(compra_id,producto_id,codigo,nombre,cantidad,costo,precio1,precio2,precio3,total)
        VALUES(docid,pid,codigo_producto,pos_privado.legacy_text(d,'nombre'),pos_privado.legacy_num(d,'cant',true)::integer,
          pos_privado.legacy_num(d,'costo'),pos_privado.legacy_num(d,'p1'),pos_privado.legacy_num(d,'p2'),pos_privado.legacy_num(d,'p3'),pos_privado.legacy_num(d,'subtotal'));
    END LOOP;
  END LOOP;
  IF NOT EXISTS(SELECT FROM public.clientes) THEN INSERT INTO public.clientes(nombre) VALUES('Cliente Contado'); END IF;
  INSERT INTO public.movimientos_inventario(producto_id,tipo,cantidad,existencia_posterior,motivo)
    SELECT id,'apertura',stock,stock,'Existencias al migrar el formato anterior' FROM public.productos WHERE stock>0;
  FOREACH tabla IN ARRAY ARRAY['clientes','suplidores','productos','ventas','venta_detalles','compras','compra_detalles','movimientos_inventario'] LOOP
    EXECUTE format('SELECT setval(pg_get_serial_sequence(%L,''id''), COALESCE(max(id),1), count(*)>0) FROM public.%I', 'public.'||tabla,tabla);
  END LOOP;
END $$;

DO $$
DECLARE tabla text; rol text;
BEGIN
  FOREACH tabla IN ARRAY ARRAY['configuracion','clientes','suplidores','productos','ventas','venta_detalles','compras','compra_detalles','movimientos_inventario'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',tabla);
    EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC',tabla);
    EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON public.%I TO pos_app',tabla);
    EXECUTE format('CREATE POLICY pos_servidor ON public.%I TO pos_app USING(true) WITH CHECK(true)',tabla);
    FOREACH rol IN ARRAY ARRAY['anon','authenticated'] LOOP
      IF EXISTS(SELECT FROM pg_roles WHERE rolname=rol) THEN EXECUTE format('REVOKE ALL ON public.%I FROM %I',tabla,rol); END IF;
    END LOOP;
  END LOOP;
  FOREACH tabla IN ARRAY ARRAY['sistema','solicitudes','respaldos'] LOOP
    EXECUTE format('ALTER TABLE pos_privado.%I ENABLE ROW LEVEL SECURITY',tabla);
    EXECUTE format('REVOKE ALL ON pos_privado.%I FROM PUBLIC',tabla);
    EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON pos_privado.%I TO pos_app',tabla);
    EXECUTE format('CREATE POLICY pos_servidor ON pos_privado.%I TO pos_app USING(true) WITH CHECK(true)',tabla);
  END LOOP;
  FOREACH tabla IN ARRAY ARRAY['clientes','suplidores','productos','ventas','venta_detalles','compras','compra_detalles','movimientos_inventario'] LOOP
    EXECUTE format('REVOKE ALL ON SEQUENCE public.%I FROM PUBLIC',tabla||'_id_seq');
    EXECUTE format('GRANT USAGE,SELECT,UPDATE ON SEQUENCE public.%I TO pos_app',tabla||'_id_seq');
    FOREACH rol IN ARRAY ARRAY['anon','authenticated'] LOOP
      IF EXISTS(SELECT FROM pg_roles WHERE rolname=rol) THEN EXECUTE format('REVOKE ALL ON SEQUENCE public.%I FROM %I',tabla||'_id_seq',rol); END IF;
    END LOOP;
  END LOOP;
END $$;
