CREATE UNIQUE INDEX productos_codigo_unico ON public.productos(lower(codigo));
CREATE TABLE public.ventas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  cliente_id bigint NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
  cliente_nombre text NOT NULL CHECK(length(btrim(cliente_nombre)) BETWEEN 1 AND 2000), cliente_rnc text NOT NULL DEFAULT '',
  fecha date NOT NULL DEFAULT (now() AT TIME ZONE 'America/Santo_Domingo')::date,
  creado_en timestamptz NOT NULL DEFAULT now(),
  tipo_comprobante text NOT NULL DEFAULT 'B02' CHECK(tipo_comprobante IN ('B01','B02','B14')),
  ncf text UNIQUE CHECK(ncf IS NULL OR length(btrim(ncf)) BETWEEN 1 AND 2000),
  condicion text NOT NULL CHECK(condicion IN ('Contado','Credito')),
  base numeric(14,2) NOT NULL CHECK(base BETWEEN 0 AND 999999999999.99),
  itbis numeric(14,2) NOT NULL CHECK(itbis BETWEEN 0 AND 999999999999.99),
  total numeric(14,2) NOT NULL CHECK(total BETWEEN 0 AND 999999999999.99),
  CHECK(base+itbis=total)
);
CREATE INDEX ventas_cliente_idx ON public.ventas(cliente_id);
CREATE INDEX ventas_fecha_idx ON public.ventas(fecha);
CREATE TABLE public.venta_detalles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  venta_id bigint NOT NULL REFERENCES public.ventas(id) ON DELETE RESTRICT,
  producto_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
  codigo text NOT NULL CHECK(length(btrim(codigo)) BETWEEN 1 AND 2000), nombre text NOT NULL CHECK(length(btrim(nombre)) BETWEEN 1 AND 2000),
  cantidad integer NOT NULL CHECK(cantidad>0),
  nivel_precio text NOT NULL CHECK(nivel_precio IN ('precio1','precio2','precio3')),
  precio numeric(14,2) NOT NULL CHECK(precio BETWEEN 0 AND 999999999999.99),
  base numeric(14,2) NOT NULL CHECK(base BETWEEN 0 AND 999999999999.99),
  itbis numeric(14,2) NOT NULL CHECK(itbis BETWEEN 0 AND 999999999999.99),
  total numeric(14,2) NOT NULL CHECK(total BETWEEN 0 AND 999999999999.99),
  CHECK(base+itbis=total AND total=precio*cantidad)
);
CREATE INDEX venta_detalles_venta_idx ON public.venta_detalles(venta_id);
CREATE INDEX venta_detalles_producto_idx ON public.venta_detalles(producto_id);
